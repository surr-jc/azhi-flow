// Makes the .claude/ layer work in OpenCode with one model per tier on your own subscription.
//   node .claude/scripts/opencode-setup.mjs <openai|github-copilot|anthropic>
//
// OpenCode already loads .claude/skills/*/SKILL.md and falls back to CLAUDE.md, but it ignores a skill's
// `model:` line. So this writes one slash command per skill into .opencode/commands/, each pinned to the
// tier's model from .claude/models.json, plus opencode.jsonc with the Atlassian MCP server if you have none.
// Re-run it after changing models.json or a skill's `model:`. It only overwrites files it generated.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../../', import.meta.url);
const skillsDir = new URL('../skills/', import.meta.url);
const models = JSON.parse(readFileSync(new URL('../models.json', import.meta.url), 'utf8'));
const providers = Object.keys(models).filter((k) => !k.startsWith('_'));
const provider = process.argv[2];
if (!providers.includes(provider)) {
  console.error(`usage: opencode-setup.mjs <${providers.join('|')}>`);
  process.exit(2);
}
const TIER = { opus: 'strong', sonnet: 'balanced', haiku: 'light' };
const MARK = '<!-- generated by .claude/scripts/opencode-setup.mjs; edit the skill or models.json, then re-run -->';
const out = new URL('.opencode/commands/', root);
mkdirSync(out, { recursive: true });

for (const name of readdirSync(skillsDir)) {
  let text;
  try {
    text = readFileSync(new URL(`${name}/SKILL.md`, skillsDir), 'utf8');
  } catch {
    continue;
  }
  const front = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] ?? '';
  const get = (k) => new RegExp(`^${k}:\\s*(.*)$`, 'm').exec(front)?.[1]?.trim().replace(/^"(.*)"$/, '$1') ?? '';
  const tier = TIER[get('model')];
  if (!tier) throw new Error(`${name}: model must be opus, sonnet or haiku`);
  const file = new URL(`${name}.md`, out);
  if (existsSync(file) && !readFileSync(file, 'utf8').includes(MARK)) {
    console.log(`skip ${name}: ${join('.opencode/commands', `${name}.md`)} is not generated`);
    continue;
  }
  const description = get('description').split(/(?<=\.)\s/)[0].replace(/"/g, "'");
  writeFileSync(
    file,
    `---\ndescription: "${description}"\nmodel: ${models[provider][tier]}\n---\n${MARK}\nLoad the \`${name}\` skill with the skill tool and follow it exactly.\nArguments: $ARGUMENTS\n`,
  );
  console.log(`/${name.padEnd(16)} ${tier.padEnd(9)} ${models[provider][tier]}`);
}

const cfg = new URL('opencode.jsonc', root);
if (!existsSync(cfg)) {
  writeFileSync(
    cfg,
    `{\n  "$schema": "https://opencode.ai/config.json",\n  // Jira and Confluence for /intake. Sign in once with: opencode mcp auth atlassian\n  "mcp": {\n    "atlassian": { "type": "remote", "url": "https://mcp.atlassian.com/v1/mcp", "enabled": true }\n  }\n}\n`,
  );
  console.log('wrote opencode.jsonc (Atlassian MCP)');
}
console.log(`\nNext: ${models[provider].label}; then restart OpenCode. Jira/Confluence: opencode mcp auth atlassian`);
